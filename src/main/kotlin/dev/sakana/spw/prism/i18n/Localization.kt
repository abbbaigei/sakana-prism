/**
 * Languages the plugin ships. [SYSTEM] means "follow the Windows UI language"; the rest are
 * explicit overrides. The set covers the six UN official languages plus Japanese, Korean and
 * Traditional Chinese.
 */
enum class AppLanguage(val code: String, val nativeName: String, val rtl: Boolean = false) {
    SYSTEM("system", "Auto"),
    ZH_HANS("zh-Hans", "简体中文"),
    ZH_HANT("zh-Hant", "繁體中文"),
    EN("en", "English"),
    FR("fr", "Français"),
    ES("es", "Español"),
    RU("ru", "Русский"),
    AR("ar", "العربية", rtl = true),
    JA("ja", "日本語"),
    KO("ko", "한국어"),
    ;

    companion object {
        fun fromCode(code: String?): AppLanguage =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: SYSTEM
    }
}

/**
 * Reads the Windows UI language through the JVM locale. Windows exposes it as
 * `Locale.getDefault()` (language + country), which is what the host JVM is started with.
 *
 * Chinese needs the script split: Windows tags Taiwan / Hong Kong / Macau as Traditional,
 * everything else as Simplified. Arabic switches the layout direction.
 */
object WindowsLanguage {

    fun detect(): AppLanguage = fromLocale(Locale.getDefault())

    fun fromLocale(locale: Locale): AppLanguage {
        val language = locale.language.lowercase(Locale.ROOT)
        val country = locale.country.uppercase(Locale.ROOT)
        return when (language) {
            "zh" -> if (country in HANT_COUNTRIES || locale.script == "Hant") AppLanguage.ZH_HANT
            else AppLanguage.ZH_HANS
            "en" -> AppLanguage.EN
            "fr" -> AppLanguage.FR
            "es" -> AppLanguage.ES
            "ru" -> AppLanguage.RU
            "ar" -> AppLanguage.AR
            "ja" -> AppLanguage.JA
            "ko" -> AppLanguage.KO
            // Anything else falls back to English rather than to Chinese.
            else -> AppLanguage.EN
        }
    }

    private val HANT_COUNTRIES = setOf("TW", "HK", "MO")
}

